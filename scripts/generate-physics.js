  const mineClasses = new Set([...body.matchAll(/\.(sds-[a-z0-9-]+)/g)].map((m) => m[1]));
  let others = "";
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".css"))) {
    let t = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const a0 = t.indexOf(START), b0 = t.indexOf(END);
    if (a0 >= 0 && b0 > a0) t = t.slice(0, a0) + t.slice(b0 + END.length);
    others += t + "\n";
  }
  const clashKf = [...mine].filter((n) => new RegExp("@keyframes\\s+" + n + "\\b").test(others));
  if (clashKf.length) throw new Error("keyframe name(s) already used by existing effects: " + clashKf.join(", "));
  const existingClasses = new Set([...others.matchAll(/\.(sds-[a-z0-9-]+)/g)].map((m) => m[1]));
  const own = new Set(["sds-char", "sds-roll", "sds-swap-old", "sds-swap-new"]); // helper classes used in markup
  const clashCls = [...mineClasses].filter((c) => existingClasses.has(c) && !own.has(c));
  if (clashCls.length) throw new Error("class name(s) already defined by existing effects: " + clashCls.join(", "));
  report.push(`  ok  no keyframe or class name collides with any existing effect (${mine.size} keyframes, ${mineClasses.size} classes checked)`);
