#!/usr/bin/env node
/**
 * SDS Motion Forge — physics text effects (v5.1).
 *
 * These effects are not hand-tuned easing. Each one is a small physical system
 * whose equations live in this file:
 *
 *   spring      m·x'' + c·x' + k·x = k            damped harmonic oscillator
 *   bounce      free fall under g, restitution e   ball on an invisible floor
 *   pendulum    θ'' + 2ζω·θ' + ω²·θ = 0            damped swing
 *   orbit       angular momentum L = r²·ω          a letter spiralling inward
 *   toss        ballistic arc, then bounces        projectile + restitution
 *   collision   approach, impact, rebound with e   two bodies meeting
 *   slosh       first two standing-wave modes      liquid surface in a glass
 *
 * Each system is sampled at high resolution, simplified (Ramer-Douglas-Peucker)
 * and written as a CSS `linear()` easing curve driving a plain from→to
 * keyframe pair. The browser then plays the physics at 60+ fps on the
 * compositor (only translate / rotate / scale / transform / filter /
 * opacity / clip-path are animated — the sds/compositor-only rule).
 * Forces drive their consequences too: skew and motion blur follow the
 * spring's *velocity*, squash follows each impact's *speed*.
 *
 * Browsers without `linear()` keep a cubic-bezier fallback; velocity-driven
 * layers use fill-mode `backwards`, so they simply vanish after the motion.
 *
 * Output goes between the @sds-physics markers at the end of
 * src/categories/text.css.   node scripts/generate-physics.js [--check]
 */
