/* ── numerics ─────────────────────────────────────────────── */
const TAU = Math.PI * 2;
const num = (x, d = 3) => String(Number(x.toFixed(d)));

/** Ramer-Douglas-Peucker on (t, y) with t pre-normalised to 0..1. */
function simplify(pts, eps) {
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let maxD = 0, idx = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b];
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i];
      const yl = y1 + ((y2 - y1) * (x - x1)) / (x2 - x1);
      const d = Math.abs(y - yl);
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > eps && idx > 0) { keep[idx] = true; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

/** Sample f over [0,T] and return a CSS linear() easing string. */
const FIDELITY = 0.007; // curve error floor: under ~0.7 % is invisible in motion and saves ~40 % of the bytes
function lin(f, T, eps = 0.004, n = 900) {
  eps = Math.max(eps, FIDELITY);
  const pts = [];
  for (let i = 0; i <= n; i++) pts.push([i / n, f((i / n) * T)]);
  const s = simplify(pts, eps);
  const parts = s.map(([x, y], i) => {
    const v = num(y, 2);
    if (i === 0 || i === s.length - 1) return v;
    return `${v} ${num(x * 100, 1)}%`;
  });
  return `linear(${parts.join(", ")})`;
}

/* ── physical systems ─────────────────────────────────────── */
/** Mass-spring-damper step response. mass, stiffness k, damping c. */
function spring({ mass = 1, k, c }) {
  const w0 = Math.sqrt(k / mass);
  const zeta = c / (2 * Math.sqrt(k * mass));
  const wd = w0 * Math.sqrt(1 - zeta * zeta);
  const a = zeta * w0;
  const x = (t) => 1 - Math.exp(-a * t) * (Math.cos(wd * t) + (a / wd) * Math.sin(wd * t));
  const v = (t) => Math.exp(-a * t) * ((w0 * w0) / wd) * Math.sin(wd * t);
  const T = Math.log(1 / 0.0015) / a; // settled to 0.15 %
  return { w0, zeta, wd, a, x, v, T, overshoot: Math.exp((-Math.PI * zeta) / Math.sqrt(1 - zeta * zeta)) };
}
/** Spring parametrised the way designers think: frequency (Hz) + damping ratio. */
const springHz = (hz, zeta) => spring({ mass: 1, k: (TAU * hz) ** 2, c: 2 * zeta * TAU * hz });

/** Ball dropped from H under g onto a floor with restitution e. Heights normalised to H. */
function bounce({ e, t0 }) {
  const flights = [];
  let t = t0;
  for (let n = 1; ; n++) {
    const apex = e ** (2 * n);
    if (apex < 0.004) break;
    const dur = e ** n * t0 * 2; // 2·v_n/g, with v_n = e^n·v0 and v0 = g·t0
    flights.push({ start: t, dur, apex });
    t += dur;
  }
  const contacts = [t0, ...flights.map((f) => f.start + f.dur)];
  const h = (tt) => {
    if (tt <= t0) return 1 - (tt / t0) ** 2;
    for (const f of flights) if (tt <= f.start + f.dur) { const u = (tt - f.start) / f.dur; return f.apex * 4 * u * (1 - u); }
    return 0;
  };
  return { T: t, h, contacts, flights, t0 };
}
/** Squash spikes at each contact, proportional to impact speed (e^i). Normalised to 1. */
function squashCurve(contacts, e, width) {
  return (t) => contacts.reduce((s, c, i) => s + e ** i * Math.exp(-(((t - c) / width) ** 2)), 0);
}

/** Projectile launched from the floor with a first-flight time D, then bounces. Heights vs first apex. */
function toss({ D, e }) {
  const flights = [{ start: 0, dur: D, apex: 1 }];
  let t = D;
  for (let n = 1; ; n++) {
    const apex = e ** (2 * n);
    if (apex < 0.01) break;
    const dur = e ** n * D;
    flights.push({ start: t, dur, apex });
    t += dur;
  }
  const contacts = flights.map((f) => f.start + f.dur);
  const h = (tt) => {
    for (const f of flights) if (tt <= f.start + f.dur) { const u = (tt - f.start) / f.dur; return f.apex * 4 * u * (1 - u); }
    return 0;
  };
  return { T: t, h, contacts, D };
}

/** Damped swing: x(t) = e^(-ζω0·t)·cos(ωd·t). */
function pendulum({ hz, zeta }) {
  const w0 = TAU * hz, wd = w0 * Math.sqrt(1 - zeta * zeta), a = zeta * w0;
  return { f: (t) => Math.exp(-a * t) * Math.cos(wd * t), T: Math.log(1 / 0.01) / a, a, wd, w0 };
}

/** Radius decays by drag; angular momentum is conserved, so ω = L/r² (capped). */
function orbit({ gamma, omega0, omegaMax, phi0, T }) {
  const dt = T / 4000, th = [phi0], r = [];
  for (let i = 0; i <= 4000; i++) {
    const rr = Math.exp(-gamma * i * dt);
    r.push(rr);
    th.push(th[i] + Math.min(omega0 / (rr * rr), omegaMax) * dt);
  }
  const at = (t) => Math.min(4000, Math.max(0, Math.round(t / dt)));
  return { x: (t) => r[at(t)] * Math.cos(th[at(t)]), y: (t) => r[at(t)] * Math.sin(th[at(t)]), T, turns: (th[4000] - phi0) / TAU };
}

/* ── verification: the numbers must match the closed-form physics ── */
function verify() {
  const out = [];
  const fail = (m) => { throw new Error("physics invariant failed: " + m); };
  const check = (label, got, want, tol) => {
    if (Math.abs(got - want) > tol) fail(`${label}: got ${got}, expected ${want}`);
    out.push(`  ok  ${label}  (${num(got, 4)} ≈ ${num(want, 4)})`);
  };
  // spring: peak of the sampled step response equals 1 + e^(−πζ/√(1−ζ²))
  for (const [hz, z] of [[2.4, 0.34], [1.7, 0.42], [1.0, 0.78]]) {
    const s = springHz(hz, z);
    let peak = 0;
    for (let i = 0; i <= 5000; i++) peak = Math.max(peak, s.x((i / 5000) * s.T));
    check(`spring ${hz}Hz ζ=${z} overshoot`, peak - 1, s.overshoot, 5e-4);
    check(`spring ${hz}Hz ζ=${z} settles to 1`, s.x(s.T), 1, 2e-3);
  }
  // spring from physical constants: ω0=√(k/m), ζ=c/(2√(km))
  const s = spring({ mass: 2, k: 800, c: 24 });
  check("spring ω0 = √(k/m)", s.w0, Math.sqrt(400), 1e-9);
  check("spring ζ = c/(2√(km))", s.zeta, 24 / (2 * Math.sqrt(1600)), 1e-9);
  // bounce: each apex is e² of the previous; total time is t0·(1 + 2e/(1−e)) (geometric series)
  const e = 0.52, b = bounce({ e, t0: 0.4 });
  check("bounce apex ratio", b.flights[1].apex / b.flights[0].apex, e * e, 1e-12);
  check("bounce total time vs geometric series", b.T, 0.4 * (1 + (2 * e) / (1 - e)), 0.4 * 2 * e ** (b.flights.length + 1) / (1 - e) + 1e-9);
  let prev = Infinity;
  for (const f of b.flights) { if (f.apex >= prev) fail("bounce energy must decrease"); prev = f.apex; }
  out.push("  ok  bounce energy decreases on every impact");
  // orbit: with r = e^(-γt) and ω = L/r² (L = ω0, r(0) = 1) until the speed cap, the swept angle is
  //   ∫ω0·e^(2γt) dt = (ωmax − ω0)/(2γ)  up to t_cap = ln(ωmax/ω0)/(2γ),  then ωmax·(T − t_cap)
  const og = { gamma: 2, omega0: 3, omegaMax: 16, phi0: 0.6, T: 1.9 };
  const o = orbit(og);
  const tCap = Math.log(og.omegaMax / og.omega0) / (2 * og.gamma);
  const exact = ((og.omegaMax - og.omega0) / (2 * og.gamma) + og.omegaMax * (og.T - tCap)) / TAU;
  check("orbit swept angle (turns) vs closed form", o.turns, exact, 2e-3);
  // bubble rise: with drag, s(t) = vt·(t − (1 − e^(−k·t))/k) reaches 1 exactly at t1, its slope at t1 equals
  // v(t1) = vt·(1 − e^(−k·t1)), and the surface spring continues from that same position and velocity (no jump)
  {
    const k = 3, t1 = 1.1, vt = 1 / (t1 - (1 - Math.exp(-k * t1)) / k), v0 = vt * (1 - Math.exp(-k * t1));
    const s = (t) => vt * (t - (1 - Math.exp(-k * t)) / k);
    check("bubble reaches the surface at t1", s(t1), 1, 1e-12);
    check("bubble arrival speed (numerical slope vs drag law)", (s(t1) - s(t1 - 1e-6)) / 1e-6, v0, 1e-4);
    check("bubble starts from rest", (s(1e-6) - s(0)) / 1e-6, 0, 1e-4);
    const z = 0.35, w0 = TAU * 3, wd = w0 * Math.sqrt(1 - z * z), a = z * w0;
    const after = (tp) => 1 + (v0 / wd) * Math.exp(-a * tp) * Math.sin(wd * tp);
    check("bubble surface spring continues at the same position", after(0), s(t1), 1e-12);
    check("bubble surface spring continues at the same speed", (after(1e-6) - after(0)) / 1e-6, v0, 1e-3);
  }
  // gravity collapse: radial infall r = r0·cos²η with t/t_fall = (η + sinη·cosη)/(π/2); progress p = sin²η
  {
    const eta = (t) => { const g = t * Math.PI / 2; let lo = 0, hi = Math.PI / 2; for (let i = 0; i < 80; i++) { const m = (lo + hi) / 2; (m + Math.sin(m) * Math.cos(m) < g) ? (lo = m) : (hi = m); } return (lo + hi) / 2; };
    const p = (t) => Math.sin(eta(t)) ** 2;
    check("infall starts at rest and ends at the attractor", p(0) + p(1), 1, 1e-9);
    // at η = π/4 the body is at half its starting radius (cos²(π/4) = ½), which happens at t/t_fall = (π/4 + ½)/(π/2)
    check("infall halfway point: η=π/4 ⇒ t/t_fall = (π/4 + ½)/(π/2)", p((Math.PI / 4 + 0.5) / (Math.PI / 2)), 0.5, 1e-9);
    // speed grows monotonically toward the attractor (inverse-square field: it accelerates, never decelerates)
    let prev = -1, mono = true;
    for (let i = 1; i < 400; i++) { const v = (p((i + 1) / 401) - p((i - 1) / 401)) / (2 / 401); if (v + 1e-9 < prev) mono = false; prev = v; }
    if (!mono) fail("infall speed must increase monotonically");
    out.push("  ok  infall accelerates monotonically (speed never drops before arrival)");
  }
  // wind drift: drag-only approach has no overshoot and arrives at 1
  {
    const tau = 0.45, T = 2.1, norm = 1 - Math.exp(-T / tau);
    let peak = 0;
    for (let i = 0; i <= 2000; i++) peak = Math.max(peak, (1 - Math.exp(-((i / 2000) * T) / tau)) / norm);
    check("wind drift never overshoots its target", peak, 1, 1e-12);
  }
  // pendulum envelope decays monotonically
  const p = pendulum({ hz: 1.3, zeta: 0.12 });
  if (!(Math.abs(p.f(p.T)) < 0.02)) fail("pendulum must be at rest after T");
  out.push("  ok  pendulum envelope decays to rest");
  return out;
}

